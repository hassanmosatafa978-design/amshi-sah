for name, title, items in (
    ("morning", "أذكار الصباح", morning),
    ("evening", "أذكار المساء", evening),
):
    path = folder / f"{name}.json"
    path.write_text(
        json.dumps({"title": title, "items": items}, ensure_ascii=False, indent=2),
        encoding="utf-8"
    )
    # Verify the written file parses correctly
    check = json.loads(path.read_text(encoding="utf-8"))
    assert check["title"] == title and len(check["items"]) == len(items)
    assert all(x.get("text") and int(x.get("count", 1)) >= 1 for x in check["items"])
    print(f"{path}: {len(check['items'])} أذكار — JSON سليم")

